#!/usr/bin/env python3
"""Write a Spectre netlist for an N-row x M-column differential crossbar.

Each weight becomes two VTEAM cells (G+ on blp<c>, G- on bln<c>), every
column gets one colout3 readout, and the bias generator (PM0 + IREF) and
sources match tb_array2x2_v4.

Example (the 2x2 array from tb_array2x2_v4):
    python3 gen_array.py --weights "2,-2;-1,3" --vin "0,0.1" \
        --colout3 ../netlists/colout3.scs > tb_array.scs
"""
import argparse
import sys

from crossbar import pair_for, parse_weights

MODELS = "/ICD/PDK/Caden/45nm/gPDK45/gpdk045_v_6_0/models/spectre/gpdk045.scs"
VTEAM_ARGS = ("ron=2e+06 roff=5e+07 voff=0.7 von=-0.7 koff=10000 "
              "kon=-10000 aoff=3 aon=3")


def netlist(weights, vin, colout3, models, vteam, sweep=None):
    rows, cols = len(weights), len(weights[0])
    if len(vin) != rows:
        raise ValueError(f"{rows} rows of weights but {len(vin)} inputs")

    params = " ".join(f"vin{i + 1}={v}" for i, v in enumerate(vin))
    lines = [
        f"// {rows}x{cols} differential VTEAM crossbar, generated by gen_array.py",
        "simulator lang=spectre",
        "global 0",
        f"parameters iref=20n vcas=400m vdd=1 vout=500m vref=300m {params}",
        f'include "{models}" section=mc',
        f'include "{colout3}"',
        f'ahdl_include "{vteam}"',
        "",
        "VDD (vdd 0) vsource dc=vdd type=dc",
        "VREF (ref 0) vsource dc=vref type=dc",
        "VCAS (cas 0) vsource dc=vcas type=dc",
        "IREF (vdp 0) isource dc=iref type=dc",
        "PM0 (vdp vdp vdd vdd) g45p1svt w=4u l=2u nf=1",
    ]
    for i in range(rows):
        lines.append(f"VIN{i + 1} (wl{i + 1} 0) vsource dc=vref+vin{i + 1} type=dc")
    for i, row in enumerate(weights):
        for c, w in enumerate(row):
            xp, xn = pair_for(w)
            for side, x in (("p", xp), ("n", xn)):
                lines.append(f"r{c + 1}_{i + 1}{side} (wl{i + 1} bl{side}{c + 1}) "
                             f"vteam {VTEAM_ARGS} xinit={x}")
    saves = []
    for c in range(cols):
        lines.append(f"VOUT{c + 1} (out{c + 1} 0) vsource dc=vout type=dc")
        lines.append(f"X{c + 1} (bln{c + 1} blp{c + 1} cas ref out{c + 1} vdd vdp) colout3")
        saves.append(f"VOUT{c + 1}:p")

    lines.append("")
    if sweep:
        name, start, stop, step = sweep
        lines.append(f"dc dc param={name} start={start} stop={stop} step={step}")
    else:
        lines.append("dcop dc")
    lines.append("save " + " ".join(saves))
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--weights", required=True,
                    help="rows separated by ';', columns by ',', integers -3..+3")
    ap.add_argument("--vin", required=True,
                    help="cell voltage per row in volts, e.g. '0,0.1'")
    ap.add_argument("--colout3", required=True, help="Spectre file defining subckt colout3")
    ap.add_argument("--models", default=MODELS)
    ap.add_argument("--vteam", default="veriloga/vteam.va")
    ap.add_argument("--sweep", nargs=4, metavar=("PARAM", "START", "STOP", "STEP"),
                    help="optional DC sweep, e.g. vin1 0 0.2 0.1")
    a = ap.parse_args()

    vin = [float(v) for v in a.vin.split(",")]
    sys.stdout.write(netlist(parse_weights(a.weights), vin, a.colout3,
                             a.models, a.vteam, a.sweep))


if __name__ == "__main__":
    main()
